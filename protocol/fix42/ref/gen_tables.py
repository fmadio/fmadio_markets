#!/usr/bin/env python3
#------------------------------------------------------------------------------
#
# gen_tables.py
#
# generates fix42_schema.h (the 1024 tag column schema + per tag value class
# table) and the fix42.md tag dictionary / message type tables from the
# QuickFIX FIX 4.2 data dictionary (FIX42.xml).
#
# usage: python3 gen_tables.py
#        writes fix42_schema.h next to itself and prints the markdown
#        fragments to stdout (manually pasted into fix42.md when the
#        dictionary changes)
#
#------------------------------------------------------------------------------

import re
import os

FIX_TAG_MAX = 1024

BASE = os.path.dirname(os.path.abspath(__file__))

xml = open(os.path.join(BASE, "FIX42.xml")).read()

# field dictionary: tag number -> (name, fix type)
fields = {}
for num, name, ftype in re.findall(r"<field number='(\d+)' name='(\w+)' type='(\w+)'", xml):
    fields[int(num)] = (name, ftype)

# message dictionary: (msgtype, name, category)
messages = re.findall(r"<message name='(\w+)' msgtype='(\w+)' msgcat='(\w+)'", xml)

#------------------------------------------------------------------------------
# FIX type -> decoder value class + parquet column type
#------------------------------------------------------------------------------

S64_TYPES    = ("INT", "DAYOFMONTH")
DOUBLE_TYPES = ("PRICE", "QTY", "AMT", "FLOAT", "PRICEOFFSET")

def tagClass(ftype):
    if ftype == "LENGTH":
        return "FIX_CLASS_LENGTH"
    if ftype == "DATA":
        return "FIX_CLASS_DATA"
    if ftype in S64_TYPES:
        return "FIX_CLASS_S64"
    if ftype in DOUBLE_TYPES:
        return "FIX_CLASS_DOUBLE"
    return "FIX_CLASS_STR"

def parquetType(ftype):
    if ftype == "LENGTH" or ftype in S64_TYPES:
        return "PARQUET_TYPE_S64"
    if ftype in DOUBLE_TYPES:
        return "PARQUET_TYPE_DOUBLE"
    return "PARQUET_TYPE_STRING"

def duckType(ftype):
    if ftype == "LENGTH" or ftype in S64_TYPES:
        return "BIGINT"
    if ftype in DOUBLE_TYPES:
        return "DOUBLE"
    return "VARCHAR"

#------------------------------------------------------------------------------
# fix42_schema.h
#------------------------------------------------------------------------------

out = []
out.append("#pragma once")
out.append("")
out.append("//------------------------------------------------------------------------------")
out.append("//")
out.append("// fix42_schema.h")
out.append("//")
out.append("// GENERATED by gen_tables.py from FIX42.xml - DO NOT EDIT.")
out.append("// one parquet column per FIX tag 1..%d (fix_<tag>), typed from the" % FIX_TAG_MAX)
out.append("// dictionary (INT family -> BIGINT, PRICE/QTY family -> DOUBLE, everything")
out.append("// else VARCHAR), plus the per tag value class table driving the decoder's")
out.append("// append and LENGTH/DATA framing. tags undefined in FIX 4.2 (gaps and")
out.append("// 447..%d) are VARCHAR catch-alls for custom/user tags." % FIX_TAG_MAX)
out.append("//")
out.append("//------------------------------------------------------------------------------")
out.append("")
out.append("#define FIX_TAG_MAX\t\t%d\t\t// columns fix_1 .. fix_%d, one per tag" % (FIX_TAG_MAX, FIX_TAG_MAX))
out.append("")
out.append("// value class per tag: drives the parquet append type and the LENGTH/DATA")
out.append("// pair framing (a DATA value's byte length comes from the immediately")
out.append("// preceding LENGTH tag and may contain SOH / arbitrary bytes)")
out.append("enum")
out.append("{")
out.append("\tFIX_CLASS_STR = 0,\t\t// VARCHAR column, value copied as string")
out.append("\tFIX_CLASS_S64,\t\t\t// BIGINT column, strtoll, parse failure -> NULL")
out.append("\tFIX_CLASS_DOUBLE,\t\t// DOUBLE column, strtod, parse failure -> NULL")
out.append("\tFIX_CLASS_LENGTH,\t\t// BIGINT column + byte length of the next DATA tag value")
out.append("\tFIX_CLASS_DATA,\t\t\t// VARCHAR column, raw bytes, length from the preceding LENGTH tag")
out.append("};")
out.append("")
out.append("//------------------------------------------------------------------------------")
out.append("// flat schema: capture layer + FIX transport + one column per tag")
out.append("//------------------------------------------------------------------------------")
out.append("static const ParquetColumn_t s_schema[] =")
out.append("{")
out.append("\t// capture layer (5-tuple + vlan + packet broker trailer), see fCapture.h")
out.append("\tCAPTURE_SCHEMA_COLUMNS")
out.append("\t// transport layer (FIX framing, not tag values)")
out.append("\t{ \"hdr_checksumValid\",    PARQUET_TYPE_U8     },\t// computed CheckSum matches tag 10: 1 ok, 0 mismatch")
out.append("\t{ \"hdr_dupTagCount\",      PARQUET_TYPE_U16    },\t// tag occurrences dropped by first-wins (repeating groups)")
out.append("\t{ \"hdr_overflowTagCount\", PARQUET_TYPE_U16    },\t// tags > FIX_TAG_MAX dropped from this message")
out.append("\t// one column per FIX tag, fix_<tag>, see fix42.md section 4 for the dictionary")

for tag in range(1, FIX_TAG_MAX + 1):
    if tag in fields:
        name, ftype = fields[tag]
        comment = "%s (%s)" % (name, ftype)
    else:
        ftype = "STRING"
        comment = "undefined in FIX 4.2, custom/user tag"
    col = "\"fix_%d\"," % tag
    out.append("\t{ %-24s %-22s},\t// %s" % (col, parquetType(ftype), comment))

out.append("};")
out.append("")
out.append("//------------------------------------------------------------------------------")
out.append("// per tag value class, indexed by tag number (0 unused). unlisted entries")
out.append("// default to FIX_CLASS_STR")
out.append("//------------------------------------------------------------------------------")
out.append("static const u8 s_tagClass[FIX_TAG_MAX + 1] =")
out.append("{")
for tag in sorted(fields):
    if tag > FIX_TAG_MAX:
        continue
    name, ftype = fields[tag]
    cls = tagClass(ftype)
    if cls == "FIX_CLASS_STR":
        continue
    out.append("\t[%d]\t= %s,\t// %s" % (tag, cls, name))
out.append("};")
out.append("")

open(os.path.join(BASE, "fix42_schema.h"), "w").write("\n".join(out))
print("wrote fix42_schema.h (%d defined tags, FIX_TAG_MAX %d)" % (len(fields), FIX_TAG_MAX))

#------------------------------------------------------------------------------
# markdown fragments (stdout)
#------------------------------------------------------------------------------

print("")
print("=== message type table ===")
print("")
print("| MsgType | Message | Category |")
print("|---------|---------|----------|")
for name, msgtype, cat in messages:
    print("| %s | %s | %s |" % (msgtype, name, cat))

print("")
print("=== tag dictionary table ===")
print("")
print("| Tag | Name | FIX Type | Column | Parquet Type |")
print("|-----|------|----------|--------|--------------|")
for tag in sorted(fields):
    name, ftype = fields[tag]
    print("| %d | %s | %s | fix_%d | %s |" % (tag, name, ftype, tag, duckType(ftype)))
